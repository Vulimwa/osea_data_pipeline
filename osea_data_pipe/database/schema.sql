CREATE TABLE IF NOT EXISTS critical_services (
  id UUID PRIMARY KEY,
  service_type TEXT NOT NULL,
  source_dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key),
  source_asset_id TEXT NOT NULL,
  source_feature_id TEXT NOT NULL,
  name TEXT,
  source_properties JSONB NOT NULL DEFAULT '{}'::jsonb,
