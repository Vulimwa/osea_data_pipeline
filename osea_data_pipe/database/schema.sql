CREATE TABLE IF NOT EXISTS climate_observations (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key),
  variable TEXT NOT NULL, value DOUBLE PRECISION, unit TEXT NOT NULL, observed_at TIMESTAMPTZ NOT NULL,
