ALTER TABLE critical_services ADD COLUMN IF NOT EXISTS last_ingested_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS service_dependencies (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  energy_asset_id UUID NOT NULL REFERENCES energy_assets(id) ON DELETE CASCADE,
  critical_service_id UUID NOT NULL REFERENCES critical_services(id) ON DELETE CASCADE,
  evidence_dataset_key TEXT REFERENCES datasets(dataset_key),
