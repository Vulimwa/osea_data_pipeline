-- OSEAS Climate Risk & Energy Infrastructure Vulnerability schema
-- PostgreSQL 14+ / Supabase with PostGIS. Safe to run repeatedly.
-- This creates OSEAS objects only; it does not drop, rename, or migrate other objects.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS datasets (
  dataset_key TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  source_type TEXT NOT NULL,
  source_reference TEXT NOT NULL,
  category TEXT NOT NULL,
  licence TEXT,
  attribution TEXT,
  is_optional BOOLEAN NOT NULL DEFAULT TRUE,
  last_ingested_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS ingestion_runs (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  pipeline_name TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('pending','running','completed','partial','failed')),
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  finished_at TIMESTAMPTZ,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  error_message TEXT
);
CREATE INDEX IF NOT EXISTS idx_oseas_ingestion_runs_started ON ingestion_runs (started_at DESC);

CREATE TABLE IF NOT EXISTS dataset_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key) ON DELETE CASCADE,
  source_reference TEXT NOT NULL,
  source_version TEXT,
  checksum TEXT,
  retrieved_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  observation_start DATE,
  observation_end DATE,
  feature_count BIGINT,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  processing_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_oseas_dataset_versions_key ON dataset_versions (dataset_key, retrieved_at DESC);

-- Source-preserving hydrography and event reference features. Additive: existing inventory and results remain intact.
CREATE TABLE IF NOT EXISTS hydrography_features (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key) ON DELETE CASCADE,
  source_feature_id TEXT NOT NULL,
  feature_type TEXT NOT NULL CHECK (feature_type IN ('river','lake','waterway','other')),
  name TEXT,
  source_properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  geom GEOMETRY(Geometry,4326) NOT NULL,
  processing_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (dataset_key, source_feature_id)
);
CREATE INDEX IF NOT EXISTS idx_oseas_hydrography_geom ON hydrography_features USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_oseas_hydrography_type ON hydrography_features (feature_type, name);

CREATE TABLE IF NOT EXISTS flood_reference_features (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key) ON DELETE CASCADE,
  source_feature_id TEXT NOT NULL,
  event_key TEXT NOT NULL,
  event_date DATE,
  source_properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  event_metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  geom GEOMETRY(Geometry,4326) NOT NULL,
  processing_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (dataset_key, source_feature_id)
);
ALTER TABLE flood_reference_features ADD COLUMN IF NOT EXISTS event_metadata JSONB NOT NULL DEFAULT '{}'::jsonb;
CREATE INDEX IF NOT EXISTS idx_oseas_flood_reference_geom ON flood_reference_features USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_oseas_flood_reference_event ON flood_reference_features (event_key, event_date);

CREATE TABLE IF NOT EXISTS data_quality_checks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id UUID REFERENCES ingestion_runs(id) ON DELETE CASCADE,
  dataset_key TEXT REFERENCES datasets(dataset_key) ON DELETE SET NULL,
  check_name TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('passed','warning','failed','not_assessed')),
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_oseas_quality_run ON data_quality_checks (run_id, checked_at DESC);

CREATE TABLE IF NOT EXISTS administrative_units (
  id UUID PRIMARY KEY,
  unit_level TEXT NOT NULL CHECK (unit_level IN ('ward','county')),
  source_dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key),
  source_asset_id TEXT NOT NULL,
  source_feature_id TEXT NOT NULL,
  stable_code TEXT,
  name TEXT,
  source_properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  geom GEOMETRY(MultiPolygon,4326) NOT NULL,
  last_ingested_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (source_dataset_key, source_feature_id)
);
CREATE INDEX IF NOT EXISTS idx_oseas_admin_geom ON administrative_units USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_oseas_admin_level_code ON administrative_units (unit_level, stable_code);
ALTER TABLE administrative_units ADD COLUMN IF NOT EXISTS last_ingested_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS energy_assets (
  id UUID PRIMARY KEY,
  asset_type TEXT NOT NULL,
  source_dataset_key TEXT NOT NULL REFERENCES datasets(dataset_key),
  source_asset_id TEXT NOT NULL,
  source_feature_id TEXT NOT NULL,
  name TEXT,
  voltage_kv DOUBLE PRECISION CHECK (voltage_kv IS NULL OR voltage_kv > 0),
  source_properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  geom GEOMETRY(Geometry,4326) NOT NULL,
  last_ingested_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL,
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (source_dataset_key, source_feature_id)
);
CREATE INDEX IF NOT EXISTS idx_oseas_energy_geom ON energy_assets USING GIST (geom);
CREATE INDEX IF NOT EXISTS idx_oseas_energy_type ON energy_assets (asset_type);
CREATE INDEX IF NOT EXISTS idx_oseas_energy_dataset ON energy_assets (source_dataset_key);
ALTER TABLE energy_assets ADD COLUMN IF NOT EXISTS last_ingested_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS asset_admin_assignments (
  id UUID PRIMARY KEY,
  energy_asset_id UUID NOT NULL REFERENCES energy_assets(id) ON DELETE CASCADE,
  administrative_unit_id UUID NOT NULL REFERENCES administrative_units(id) ON DELETE CASCADE,
  unit_level TEXT NOT NULL CHECK (unit_level IN ('ward','county')),
  relation_method TEXT NOT NULL CHECK (relation_method IN ('point_covered_by','boundary_intersection')),
  intersection_length_m DOUBLE PRECISION CHECK (intersection_length_m IS NULL OR intersection_length_m >= 0),
  intersection_area_m2 DOUBLE PRECISION CHECK (intersection_area_m2 IS NULL OR intersection_area_m2 >= 0),
  is_current BOOLEAN NOT NULL DEFAULT TRUE,
  processing_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (energy_asset_id, administrative_unit_id)
);
CREATE INDEX IF NOT EXISTS idx_oseas_asset_admin_unit ON asset_admin_assignments (administrative_unit_id, unit_level);

CREATE TABLE IF NOT EXISTS network_lines (
  asset_id UUID PRIMARY KEY REFERENCES energy_assets(id) ON DELETE CASCADE,
