-- Coverage is an observation property, not a hazard score; retain observed and valid footprints separately.
CREATE TABLE IF NOT EXISTS spatial_coverage_assessments (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  dataset_key TEXT REFERENCES datasets(dataset_key) ON DELETE SET NULL,
  processing_run_id UUID REFERENCES ingestion_runs(id) ON DELETE SET NULL,
  reporting_unit_id UUID REFERENCES administrative_units(id) ON DELETE SET NULL,
  reporting_unit_level TEXT CHECK (reporting_unit_level IS NULL OR reporting_unit_level IN ('national','county','ward','asset','network_segment')),
  hazard_type TEXT,
  evidence_kind TEXT CHECK (evidence_kind IS NULL OR evidence_kind IN ('observed','modeled','inferred','scenario','resource')),
  observation_start TIMESTAMPTZ,
  observation_end TIMESTAMPTZ,
  coverage_status TEXT NOT NULL CHECK (coverage_status IN ('not_assessed','insufficient_data','partially_assessed','assessed','blocked','scientifically_validated')),
  area_coverage_fraction DOUBLE PRECISION CHECK (area_coverage_fraction IS NULL OR area_coverage_fraction BETWEEN 0 AND 1),
  valid_data_fraction DOUBLE PRECISION CHECK (valid_data_fraction IS NULL OR valid_data_fraction BETWEEN 0 AND 1),
  observation_footprint GEOMETRY(Geometry,4326),
  valid_data_footprint GEOMETRY(Geometry,4326),
  quality_mask JSONB NOT NULL DEFAULT '{}'::jsonb,
  validation_status TEXT NOT NULL DEFAULT 'not_validated',
  limitations JSONB NOT NULL DEFAULT '[]'::jsonb,
  provenance JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_oseas_coverage_observation_geom ON spatial_coverage_assessments USING GIST (observation_footprint);
CREATE INDEX IF NOT EXISTS idx_oseas_coverage_valid_geom ON spatial_coverage_assessments USING GIST (valid_data_footprint);
CREATE INDEX IF NOT EXISTS idx_oseas_coverage_unit ON spatial_coverage_assessments (reporting_unit_level, reporting_unit_id, created_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS ux_oseas_coverage_run_scope ON spatial_coverage_assessments
  (processing_run_id, COALESCE(dataset_key,''), COALESCE(reporting_unit_id,'00000000-0000-0000-0000-000000000000'::uuid), COALESCE(hazard_type,''), coverage_status)
  WHERE processing_run_id IS NOT NULL;

