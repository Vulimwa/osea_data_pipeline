CREATE INDEX IF NOT EXISTS idx_oseas_climate_proj_geom ON climate_projections USING GIST (geom);

CREATE TABLE IF NOT EXISTS hazard_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(), hazard_type TEXT NOT NULL,
  evidence_kind TEXT NOT NULL CHECK (evidence_kind IN ('observed','modeled','inferred','scenario')),
